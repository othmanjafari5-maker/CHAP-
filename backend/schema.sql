CREATE TABLE IF NOT EXISTS ambulances (
 id SERIAL PRIMARY KEY, ambulance_code VARCHAR(50) UNIQUE NOT NULL,
 registration_number VARCHAR(100), hospital_name VARCHAR(200),
 status VARCHAR(50) NOT NULL DEFAULT 'available', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS vehicle_readings (
 id SERIAL PRIMARY KEY, ambulance_id INTEGER NOT NULL REFERENCES ambulances(id),
 latitude NUMERIC, longitude NUMERIC, speed NUMERIC, rpm INTEGER,
 engine_temperature NUMERIC, battery_voltage NUMERIC, fuel_level NUMERIC, vibration NUMERIC,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS vehicle_alerts (
 id SERIAL PRIMARY KEY, ambulance_id INTEGER REFERENCES ambulances(id), alert_type VARCHAR(100),
 severity VARCHAR(30), message TEXT, sensor_value NUMERIC, status VARCHAR(30) DEFAULT 'ACTIVE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, resolved_at TIMESTAMP
);
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS event_id TEXT;
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS recorded_at TIMESTAMPTZ;
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS received_at TIMESTAMPTZ;
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS odometer_km NUMERIC;
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS fault_codes JSONB;
ALTER TABLE vehicle_readings ADD COLUMN IF NOT EXISTS source TEXT DEFAULT 'device';
-- Legacy timestamps were generated by the database in its configured timezone.
UPDATE vehicle_readings SET recorded_at = created_at AT TIME ZONE current_setting('TIMEZONE') WHERE recorded_at IS NULL;
UPDATE vehicle_readings SET received_at = created_at AT TIME ZONE current_setting('TIMEZONE') WHERE received_at IS NULL OR event_id IS NULL;
ALTER TABLE vehicle_readings ALTER COLUMN received_at SET DEFAULT CURRENT_TIMESTAMP;
CREATE UNIQUE INDEX IF NOT EXISTS reading_event_unique ON vehicle_readings(ambulance_id, event_id);
CREATE INDEX IF NOT EXISTS reading_observation_idx ON vehicle_readings(ambulance_id, recorded_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS safety_holds (
 id SERIAL PRIMARY KEY, ambulance_id INTEGER NOT NULL REFERENCES ambulances(id),
 reason TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT NOW(), cleared_at TIMESTAMPTZ,
 cleared_by TEXT, clearance_notes TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_hold ON safety_holds(ambulance_id) WHERE cleared_at IS NULL;
CREATE TABLE IF NOT EXISTS maintenance_records (
 id SERIAL PRIMARY KEY, ambulance_id INTEGER NOT NULL REFERENCES ambulances(id),
 service_date DATE NOT NULL, odometer_km NUMERIC NOT NULL CHECK(odometer_km >= 0),
 repair_type TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '', fault_codes JSONB NOT NULL DEFAULT '[]',
 next_service_date DATE NOT NULL, next_service_km NUMERIC,
 failure_occurred BOOLEAN NOT NULL DEFAULT FALSE, created_by TEXT NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS maintenance_vehicle_idx ON maintenance_records(ambulance_id, service_date DESC, id DESC);
CREATE TABLE IF NOT EXISTS coverage_settings (
 hospital_name TEXT PRIMARY KEY, minimum_ready INTEGER NOT NULL DEFAULT 1 CHECK(minimum_ready >= 1)
);
